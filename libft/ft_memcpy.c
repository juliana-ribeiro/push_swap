#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	unsigned char	*c_dest;
	unsigned char	*c_src;

	c_dest = (unsigned char *)dest;
	c_src = (unsigned char *)src;
	if (!dest || !src)
		return (NULL);
	while (n--)
	{
		*c_dest++ = *c_src++;
	}
	return (dest);
}
