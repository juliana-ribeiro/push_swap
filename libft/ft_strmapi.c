#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned
int, char))
{
	char	*new_str;
	size_t	i;

	if (!s || !f)
		return (NULL);
	i = 0;
	new_str = (char *)malloc(sizeof(char) * ft_strlen(s) + 1);
	while (s[i])
	{
		new_str[i] = f(i, s[i]);
		i++;
	}
	new_str[i] = '\0';
	return (new_str);
}
